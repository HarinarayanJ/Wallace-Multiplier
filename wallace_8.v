`timescale 1ns / 1ps

module wallace_8bit(input [7:0] A, B, output [15:0] C);
    
    // Step 1: Partial Products
    
    wire [7:0] P [7:0];
    
    genvar i;
    generate 
        for (i=0; i<8; i = i + 1) begin: p_gen
            assign P[i] = (A & {8{B[i]}});
        end
    endgenerate
    
    // Step 2: Wallace Reduction
    
    
    // Stage 1: 8 ins - 3 parts - 6 outs
    
    wire [9:0] S1_1, S1_3;
    wire [7:0] S1_2, S1_4, S1_5, S1_6;
    
        // Part 1
    assign S1_1[0] = P[0][0];
    assign S1_1[9] = P[2][7];
    
    HA s111h (.A(P[0][1]), .B(P[1][0]), .C_(S1_2[0]), .S(S1_1[1]));
    FA s111f (.A(P[0][2]), .B(P[2][0]), .C(P[1][1]), .C_(S1_2[1]), .S(S1_1[2]));
    FA s112f (.A(P[0][3]), .B(P[2][1]), .C(P[1][2]), .C_(S1_2[2]), .S(S1_1[3]));
    FA s113f (.A(P[0][4]), .B(P[2][2]), .C(P[1][3]), .C_(S1_2[3]), .S(S1_1[4]));
    FA s114f (.A(P[0][5]), .B(P[2][3]), .C(P[1][4]), .C_(S1_2[4]), .S(S1_1[5]));
    FA s115f (.A(P[0][6]), .B(P[2][4]), .C(P[1][5]), .C_(S1_2[5]), .S(S1_1[6]));
    FA s116f (.A(P[0][7]), .B(P[2][5]), .C(P[1][6]), .C_(S1_2[6]), .S(S1_1[7]));
    HA s112h (.A(P[1][7]), .B(P[2][6]), .C_(S1_2[7]), .S(S1_1[8]));
    
        // Part 2
    assign S1_3[0] = P[3][0];
    assign S1_3[9] = P[5][7];
    
    HA s121h (.A(P[3][1]), .B(P[4][0]), .C_(S1_4[0]), .S(S1_3[1]));
    FA s121f (.A(P[3][2]), .B(P[5][0]), .C(P[4][1]), .C_(S1_4[1]), .S(S1_3[2]));
    FA s122f (.A(P[3][3]), .B(P[5][1]), .C(P[4][2]), .C_(S1_4[2]), .S(S1_3[3]));
    FA s123f (.A(P[3][4]), .B(P[5][2]), .C(P[4][3]), .C_(S1_4[3]), .S(S1_3[4]));
    FA s124f (.A(P[3][5]), .B(P[5][3]), .C(P[4][4]), .C_(S1_4[4]), .S(S1_3[5]));
    FA s125f (.A(P[3][6]), .B(P[5][4]), .C(P[4][5]), .C_(S1_4[5]), .S(S1_3[6]));
    FA s126f (.A(P[3][7]), .B(P[5][5]), .C(P[4][6]), .C_(S1_4[6]), .S(S1_3[7]));
    HA s122h (.A(P[4][7]), .B(P[5][6]), .C_(S1_4[7]), .S(S1_3[8]));
    
        // Part 3
    assign S1_5 = P[6];
    assign S1_6 = P[7];
    
    
    // Stage 2: 6 ins - 2 parts - 4 outs
    
    wire [10:0] S2_1;
    wire [9:0] S2_2, S2_3;
    wire [7:0] S2_4;
    
        // Part 1
    assign S2_1[0] = S1_1[0];
    assign S2_1[1] = S1_1[1];
    assign S2_1[10] = S1_3[7];
    assign S2_2[8] = S1_3[8];
    assign S2_2[9] = S1_3[9];
   
    HA s211h (.A(S1_1[2]), .B(S1_2[0]), .C_(S2_2[0]), .S(S2_1[2]));
    FA s211f (.A(S1_1[3]), .B(S1_2[1]), .C(S1_3[0]), .C_(S2_2[1]), .S(S2_1[3]));
    FA s212f (.A(S1_1[4]), .B(S1_2[2]), .C(S1_3[1]), .C_(S2_2[2]), .S(S2_1[4]));
    FA s213f (.A(S1_1[5]), .B(S1_2[3]), .C(S1_3[2]), .C_(S2_2[3]), .S(S2_1[5]));
    FA s214f (.A(S1_1[6]), .B(S1_2[4]), .C(S1_3[3]), .C_(S2_2[4]), .S(S2_1[6]));
    FA s215f (.A(S1_1[7]), .B(S1_2[5]), .C(S1_3[4]), .C_(S2_2[5]), .S(S2_1[7]));
    FA s216f (.A(S1_1[8]), .B(S1_2[6]), .C(S1_3[5]), .C_(S2_2[6]), .S(S2_1[8]));
    FA s217f (.A(S1_1[9]), .B(S1_2[7]), .C(S1_3[6]), .C_(S2_2[7]), .S(S2_1[9]));
    
        // Part 2
    assign S2_3[0] = S1_4[0];
    assign S2_3[9] = S1_6[7];
    
    HA s221h (.A(S1_4[1]), .B(S1_5[0]), .C_(S2_4[0]), .S(S2_3[1]));
    FA s221f (.A(S1_4[2]), .B(S1_5[1]), .C(S1_6[0]), .C_(S2_4[1]), .S(S2_3[2]));
    FA s222f (.A(S1_4[3]), .B(S1_5[2]), .C(S1_6[1]), .C_(S2_4[2]), .S(S2_3[3]));
    FA s223f (.A(S1_4[4]), .B(S1_5[3]), .C(S1_6[2]), .C_(S2_4[3]), .S(S2_3[4]));
    FA s224f (.A(S1_4[5]), .B(S1_5[4]), .C(S1_6[3]), .C_(S2_4[4]), .S(S2_3[5]));
    FA s225f (.A(S1_4[6]), .B(S1_5[5]), .C(S1_6[4]), .C_(S2_4[5]), .S(S2_3[6]));
    FA s226f (.A(S1_4[7]), .B(S1_5[6]), .C(S1_6[5]), .C_(S2_4[6]), .S(S2_3[7]));
    HA s222h (.A(S1_5[7]), .B(S1_6[6]), .C_(S2_4[7]), .S(S2_3[8]));
    
    
    // Stage 3: 4 ins - 2 parts - 3 outs
    
    wire [13:0] S3_1;
    wire [10:0] S3_2;
    wire [7:0] S3_3;
    
        // Part 1
    assign S3_1[0] = S2_1[0];
    assign S3_1[1] = S2_1[1];
    assign S3_1[2] = S2_1[2];
    assign S3_1[13] = S2_3[8];
    assign S3_2[10] = S2_3[9];
    
    HA s311h (.A(S2_1[3]), .B(S2_2[0]), .C_(S3_2[0]), .S(S3_1[3]));
    HA s312h (.A(S2_1[4]), .B(S2_2[1]), .C_(S3_2[1]), .S(S3_1[4]));
    FA s311f (.A(S2_1[5]), .B(S2_2[2]), .C(S2_3[0]), .C_(S3_2[2]), .S(S3_1[5]));
    FA s312f (.A(S2_1[6]), .B(S2_2[3]), .C(S2_3[1]), .C_(S3_2[3]), .S(S3_1[6]));
    FA s313f (.A(S2_1[7]), .B(S2_2[4]), .C(S2_3[2]), .C_(S3_2[4]), .S(S3_1[7]));
    FA s314f (.A(S2_1[8]), .B(S2_2[5]), .C(S2_3[3]), .C_(S3_2[5]), .S(S3_1[8]));
    FA s315f (.A(S2_1[9]), .B(S2_2[6]), .C(S2_3[4]), .C_(S3_2[6]), .S(S3_1[9]));
    FA s316f (.A(S2_1[10]), .B(S2_2[7]), .C(S2_3[5]), .C_(S3_2[7]), .S(S3_1[10]));
    HA s313h (.A(S2_3[6]), .B(S2_2[8]), .C_(S3_2[8]), .S(S3_1[11]));
    HA s314h (.A(S2_3[7]), .B(S2_2[9]), .C_(S3_2[9]), .S(S3_1[12]));
    
        // Part 2
    assign S3_3 = S2_4;
    
    
    // Stage 4: 3 ins - 1 part - 2 outs
    
    wire [14:0] S4_1;
    wire [10:0] S4_2;
    
        // Part 1
    assign S4_1[0] = S3_1[0]; 
    assign S4_1[1] = S3_1[1]; 
    assign S4_1[2] = S3_1[2]; 
    assign S4_1[3] = S3_1[3]; 
      
    HA s411h (.A(S3_1[4]), .B(S3_2[0]), .C_(S4_2[0]), .S(S4_1[4]));
    HA s412h (.A(S3_1[5]), .B(S3_2[1]), .C_(S4_2[1]), .S(S4_1[5]));
    HA s413h (.A(S3_1[6]), .B(S3_2[2]), .C_(S4_2[2]), .S(S4_1[6]));
    FA s411f (.A(S3_1[7]), .B(S3_2[3]), .C(S3_3[0]), .C_(S4_2[3]), .S(S4_1[7]));
    FA s412f (.A(S3_1[8]), .B(S3_2[4]), .C(S3_3[1]), .C_(S4_2[4]), .S(S4_1[8]));
    FA s413f (.A(S3_1[9]), .B(S3_2[5]), .C(S3_3[2]), .C_(S4_2[5]), .S(S4_1[9]));
    FA s414f (.A(S3_1[10]), .B(S3_2[6]), .C(S3_3[3]), .C_(S4_2[6]), .S(S4_1[10]));
    FA s415f (.A(S3_1[11]), .B(S3_2[7]), .C(S3_3[4]), .C_(S4_2[7]), .S(S4_1[11]));
    FA s416f (.A(S3_1[12]), .B(S3_2[8]), .C(S3_3[5]), .C_(S4_2[8]), .S(S4_1[12]));
    FA s417f (.A(S3_1[13]), .B(S3_2[9]), .C(S3_3[6]), .C_(S4_2[9]), .S(S4_1[13]));
    HA s414h (.A(S3_3[7]), .B(S3_2[10]), .C_(S4_2[10]), .S(S4_1[14]));
    

    // Step 3: Final Addition
    wire [15:0] S; 
    wire [9:0] C_;
    wire C_F;
    
    assign S[0] = S4_1[0];
    assign S[1] = S4_1[1];
    assign S[2] = S4_1[2];
    assign S[3] = S4_1[3];
    assign S[4] = S4_1[4];

    // Addition of final two parts
    HA s5 (.A(S4_1[5]), .B(S4_2[0]), .C_(C_[0]), .S(S[5]));
    FA s6 (.A(S4_1[6]), .B(S4_2[1]), .C(C_[0]), .C_(C_[1]), .S(S[6]));
    FA s7 (.A(S4_1[7]), .B(S4_2[2]), .C(C_[1]), .C_(C_[2]), .S(S[7]));
    FA s8 (.A(S4_1[8]), .B(S4_2[3]), .C(C_[2]), .C_(C_[3]), .S(S[8]));
    FA s9 (.A(S4_1[9]), .B(S4_2[4]), .C(C_[3]), .C_(C_[4]), .S(S[9]));
    FA s10 (.A(S4_1[10]), .B(S4_2[5]), .C(C_[4]), .C_(C_[5]), .S(S[10]));
    FA s11 (.A(S4_1[11]), .B(S4_2[6]), .C(C_[5]), .C_(C_[6]), .S(S[11]));
    FA s12 (.A(S4_1[12]), .B(S4_2[7]), .C(C_[6]), .C_(C_[7]), .S(S[12]));
    FA s13 (.A(S4_1[13]), .B(S4_2[8]), .C(C_[7]), .C_(C_[8]), .S(S[13]));
    FA s14 (.A(S4_1[14]), .B(S4_2[9]), .C(C_[8]), .C_(C_[9]), .S(S[14]));
    HA s15 (.A(C_[9]), .B(S4_2[10]), .C_(C_F), .S(S[15]));
    
    assign C = S;
    
endmodule

// Adders
module FA(input A, B, C, output C_, S);

    assign C_ = (A&B)|(A&C)|(B&C);
    assign S = A^B^C;
    
endmodule

module HA(input A, B, output C_, S);
    
    assign C_ = A&B;
    assign S = A^B;
    
endmodule